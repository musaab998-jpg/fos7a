// Every phone that hosts remembers which questions it has already shown, in any room and any game, so a
// new room starts with questions this host hasn't seen, then the ones it saw longest ago. Kept on the phone
// only, as a short hash of the question and when it was last asked, trimmed to the newest few thousand.
const QSEEN_KEY = "fos7a.qseen.v1", QSEEN_MAX = 4000;
let QSEEN = null;
const qHash = (t) => { let h = 5381; for (let i = 0; i < t.length; i++) h = ((h << 5) + h + t.charCodeAt(i)) | 0; return (h >>> 0).toString(36); };
function qSeen() {
  if (!QSEEN) { try { QSEEN = JSON.parse(localStorage.getItem(QSEEN_KEY) || "{}") || {}; } catch (e) { QSEEN = {}; } }
  return QSEEN;
}
function qMark(t) {
  const m = qSeen(); m[qHash(t)] = Date.now();
  const ks = Object.keys(m);
  if (ks.length > QSEEN_MAX) ks.sort((x, y) => m[x] - m[y]).slice(0, ks.length - QSEEN_MAX).forEach((k) => delete m[k]);
  try { localStorage.setItem(QSEEN_KEY, JSON.stringify(m)); } catch (e) {}
}

// Picks a question from a category. `used` is a Set the host keeps for the whole room, shared by every game
// played in it, so no question comes back in the same room until its category runs out. Among the room's
// fresh questions, ones this phone never showed come first, then the third it showed longest ago.
// Options come back shuffled with the answer re-pointed.
function drawQuestion(cat, used) {
  const bank = QBANK[cat] || QBANK["عامة"];
  let fresh = bank.filter((x) => !used.has(x[0]));
  if (!fresh.length) { bank.forEach((x) => used.delete(x[0])); fresh = bank; }
  const m = qSeen(), when = (x) => m[qHash(x[0])] || 0;
  const never = fresh.filter((x) => !when(x));
  const pool = never.length ? never : fresh.slice().sort((x, y) => when(x) - when(y)).slice(0, Math.max(1, Math.ceil(fresh.length / 3)));
  const [q, o, a, w] = pool[Math.floor(Math.random() * pool.length)];
  used.add(q); qMark(q);
  const order = shuffled(o.map((_, k) => k));
  return { q, cat, o: order.map((k) => o[k]), a: a < 0 ? -1 : order.indexOf(a), w: w ? order.map((k) => w[k]) : null };
}
