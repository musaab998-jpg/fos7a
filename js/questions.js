// Picks a question from a category, never the same one twice in a room until the category runs out.
// `used` is a Set kept by the host for the whole room; options come back shuffled with the answer re-pointed.
function drawQuestion(cat, used) {
  const bank = QBANK[cat] || QBANK["عامة"];
  let fresh = bank.filter((x) => !used.has(x[0]));
  if (!fresh.length) { bank.forEach((x) => used.delete(x[0])); fresh = bank; }
  const [q, o, a, w] = fresh[Math.floor(Math.random() * fresh.length)];
  used.add(q);
  const order = shuffled(o.map((_, k) => k));
  return { q, cat, o: order.map((k) => o[k]), a: a < 0 ? -1 : order.indexOf(a), w: w ? order.map((k) => w[k]) : null };
}
