// o.more = show the fine print folded under the steps; o.tv = the big-screen layout
function howHTML(id, o = {}) {
  const g = ROOM_GAMES[id], h = HOW[id];
  if (!g) return "";
  if (!h) return `<ol class="rules">${g.rules.map((r) => `<li>${r}</li>`).join("")}</ol>`;
  return `<div class="how ${o.tv ? "tv" : ""}">
    <div class="how-goal"><span>الهدف</span>${h.goal}</div>
    <div class="how-steps">${h.steps.map(([t, d], k) => `<div class="how-step"><b class="how-n">${AR(k + 1)}</b><div><b>${t}</b><span>${d}</span></div></div>`).join("")}</div>
    ${o.more !== false && !o.tv ? `<details class="how-more"><summary>التفاصيل والنقاط</summary><ol class="rules">${g.rules.map((r) => `<li>${r}</li>`).join("")}</ol></details>` : ""}
  </div>`;
}
// «؟» in a game, and «طريقة اللعب» on a game card
function openHow(id) {
  const g = ROOM_GAMES[id]; if (!g) return;
  $("modalCard").innerHTML = `<h3>طريقة اللعب: ${g.name}</h3>${howHTML(id)}<button type="button" class="pbtn" id="mClose">فهمت</button>`;
  $("modal").hidden = false;
  $("mClose").onclick = () => ($("modal").hidden = true);
}
$("howBtn").onclick = () => openHow((KL.S && KL.S.game) || current);
